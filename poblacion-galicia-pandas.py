# Defino los cortes exactos que pide la consigna (INE)
cortes_ine = [0, 16, 25, 35, 45, 55, 65, 100]
etiquetas_ine = ['0-15', '16-24', '25-34', '35-44', '45-54', '55-64', '65+']

