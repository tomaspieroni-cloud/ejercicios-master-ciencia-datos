"""# **Análisis de los datos**
La idea es quedarnos con información no redundante y aquella que podamos disponer todos los años desde 1971.
"""

# Definición de criterios para limpiar el dataset
# Quiero eliminar lo que el profesor denomina información redundante o inconsistente.

# Identifico las filas que voy a borrar:
# - Sexo == "Total": Es redundante porque ya tengo Hombres y Mujeres por separado.
# - Edad: Quito 'Todas las edades' y los desgloses de más de 85 años (86, 87...)
# - Provincia == 'Total Nacional': No me interesa para un estudio por provincias.
# - Periodo: Solo quiero la foto fija del '1 de enero' de cada año para ver la evolución anual.

borrar = (
    (datos.Sexo == "Total") |
    datos.Edad.str.startswith(('Todas las edades', '85 años', '86 años', '87 años',
                               '88 años', '89 años', '90 años', '91 años', '92 años', '93 años',
                               '94 años', '95 años', '96 años', '97 años', '98 años', '99 años',
                               '100 y más años')) |
    (datos.Provincia == 'Total Nacional') |
    (~datos.Periodo.str.contains('enero'))
)

# Aplico el filtro:
# Me quedo con todo lo que NO cumple las condiciones anteriores (usando el operador ~)
datos = datos[~borrar]

# Reindizo el DataFrame:
# Como he borrado muchas filas, el índice ha quedado con saltos.
# Lo reseteo para que vuelva a ser correlativo (0, 1, 2...).
datos.reset_index(drop=True, inplace=True)

# Verifico cuántos datos me quedan y cómo se ven las primeras filas
print("Tamaño tras la limpieza:", datos.shape)
print(datos.head())

"""# **Columna Edad**

La idea sería eliminar 0 años, 1 año, ... 85 y más años y quedarnos solo con el número, y luego convertirlo a valor numérico entero, pues se maneja mejor.
"""

# Hago una copia profunda de la columna Edad para trabajar sobre ella de forma segura
edad_aux = deepcopy(datos.Edad)

# Uso una expresión regular (Regex) para limpiar el texto.
# El patrón r'\D' identifica cualquier carácter que NO sea un número y lo borra.
# Así, '85 y más años' se convierte en '85' y '0 años' en '0'.
edad_aux = edad_aux.str.replace(r'\D', '', regex=True)

# Asigno estos valores limpios a mi DataFrame original
datos.Edad = edad_aux
del edad_aux

#Convierto la columna a tipo entero (np.int16).
datos.Edad = datos.Edad.astype(np.int16)

# Verifico que la transformación sea correcta
print("Tipo de dato final de Edad:", datos.Edad.dtype)
print(np.sort(datos.Edad.unique()))

"""# **Columna Provincia**"""

# Hago una copia profunda de la columna Provincia para trabajar con seguridad
provincia_aux = deepcopy(datos.Provincia)

# Uso una expresión regular para limpiar los nombres de un solo golpe.
# El patrón r'\d+ ' busca:uno o más dígitos numéricos al principio
# y el espacio en blanco que separa el número del nombre
# Todo lo que coincida con este patrón lo borro (lo reemplazo por nada).

provincia_aux = provincia_aux.str.replace(r'\d+ ', '', regex=True)

#Verifico que el resultado sea el esperado (solo nombres de provincias)
print(provincia_aux.unique())

# Asigno los valores nuevos a mi DataFrame principal
datos.Provincia = provincia_aux
del provincia_aux
print(datos[['Provincia', 'Edad', 'Periodo']].head())

"""Ahora tengo nombres limpios

# **PERIODO**
"""

#Hago una copia de la columna Periodo para trabajar con seguridad
periodo_aux = deepcopy(datos.Periodo)

# Elimino el texto "1 de enero de " para dejar solo el año
# Al ser todos los datos del 1 de enero, esta limpieza es uniforme
datos.Periodo = periodo_aux.str.replace('1 de enero de ', '')

# Borro la variable auxiliar ya que no la necesito más
del periodo_aux

# Convierto la columna a entero (int16) para que sea un número real
# Esto me permitirá hacer cálculos y que el eje X de mis gráficas sea correcto
datos.Periodo = datos.Periodo.astype(np.int16)
datos.info()
print(f"Desde {datos.Periodo.min()} hasta {datos.Periodo.max()}")

"""# **TOTAL**

Si usara un entero pequeño como int16, las poblaciones de provincias grandes como Madrid o Barcelona no cabrían y el código daría error o datos erróneos. Por eso, voy a usar np.int32, que ermite manejar cifras de hasta 2.000 millones
"""

total_aux = deepcopy(datos.Total)

# Elimino los puntos que funcionan como separadores de miles
datos.Total = total_aux.str.replace('.', '', regex=False)
del total_aux

# Convierto la columna a entero de 32 bits (np.int32)
# Elijo este tipo de dato para evitar el desbordamiento, ya que hay provincias con millones de habitantes.
datos.Total = datos.Total.astype(np.int32)

# Verifico la estructura final
datos.info()
