provincias_galicia = ['Coruña, A', 'Lugo', 'Ourense', 'Pontevedra']
datos_galicia = datos[datos.Provincia.isin(provincias_galicia)]

# Creo la Tabla Pivot para A Coruña con estos nuevos grupos
