"""**El Mapa de Calor (Heatmap):**

Muestra envejecimiento poblacional de forma evidente. En la columna 0-15 en 1971 está en rojo intenso. A medida que vamos hacia 2025, se vuelve amarilla. Se ha reducido abruptamente la natalidad.

En la columna 65+ (derecha) ocurre lo contrario. Empieza amarillo en los 70 y termina en rojo oscuro en 2025.

La "masa" de población se ha desplazado de la infancia a la vejez, ya que el componente principal en el último dato disponible es principalmente en la franja de edad mayores a 65+.

**Las Barras Apiladas:**

El eje X, la población total de La Coruña ha pasado de un poco más de 1.000.000 a casi 1.150.000. Ha crecido.

Aunque la estructura interna ha cambiado (menos segmento azul 0-15, mucho más segmento rosa 65+), la provincia ha ganado habitantes. Lo que cambio fue la composición, la población ha envejecido notoriamente.

*Para demostrar si Santiago (A Coruña) es un "polo atractor", lo que nos interesa ver es si el bloque central (Activos 16-65) crece o se mantiene fuerte comparado con el resto de provincias.*
"""

# Defino los intervalos de actividad económica
# 0-15 (Jóvenes), 16-65 (Activos), 66+ (No activos/Jubilados)
intervalos_actividad = [0, 16, 66, 100]
etiquetas_actividad = ['Jóvenes', 'Activos', 'No Activos']

# Creo la columna 'GrupoActividad' usando pd.cut
datos['GrupoActividad'] = pd.cut(datos.Edad,
                                 bins=intervalos_actividad,
                                 right=False,
                                 labels=etiquetas_actividad)

# Creo la Tabla Pivot Específica para A Coruña
provincia_capital = 'Coruña, A'
datos_capital = datos[datos.Provincia == provincia_capital]

tablapivot_actividad = datos_capital.pivot_table(values='Total',
                                                 index='Periodo',
                                                 columns='GrupoActividad',
                                                 aggfunc='sum',
                                                 observed=True)

# Barras Apiladas
tablapivot_actividad.plot.barh(stacked=True,
                               legend=True,
                               title='Población por Actividad en ' + provincia_capital,
                               figsize=(8, 10))

plt.xlabel('Número de Habitantes')
plt.show()

"""Barra Naranja (Activos 16-65): Es el bloque más grande. Su anchura total (cantidad de personas) ha crecido desde 1971 y se mantiene muy sólida. Si A Coruña estuviera drececiendo, esta franja naranja se habría estrechado mucho más.

Barra Verde (No Activos 66+): Crece, en contraposición con la barra azul (Jóvenes).

La carga sobre la población activa es mayor (hay más verdes por cada naranja), pero el volumen total de fuerza laboral en la capital sigue siendo alto.

# **CORRELACION**

El código es para analizar específicamente la Población Activa (16-65 años) porque si **A Coruña** actúa como "polo atractor" economico, se debería notar mas en la gente que busca trabajo o trabaja que en los jubilados.

Cuando la población de la capital cambia, ¿qué pasa al mismo tiempo con la población del resto de la comunidad?

La correlación permite evaluar si el crecimiento de la capital está asociado al crecimiento o al decrecimiento demográfico del resto de las provincias, ofreciendo una aproximación al posible efecto de "polo atractor."
"""

from scipy import stats

# Preparo los datos: Comparativa de Población ACTIVA (16-65 años)
# Separo los datos de la capital frente a la suma de las otras tres provincias.
# Filtro los Activos para A Coruña
activos_coruna = datos[(datos.Provincia == 'Coruña, A') &
                       (datos.GrupoActividad == 'Activos')].groupby('Periodo')['Total'].sum()

# Filtro los Activos para el Resto de Galicia (Lugo, Ourense, Pontevedra)
activos_resto = datos[(datos.Provincia.isin(['Lugo', 'Ourense', 'Pontevedra'])) &
                      (datos.GrupoActividad == 'Activos')].groupby('Periodo')['Total'].sum()

# Alineo los datos en un DataFrame común
comparativa_ols = pd.DataFrame({
    'Capital_Activos': activos_coruna,
    'Resto_Activos': activos_resto
}).dropna()

# Defino X (Capital) e Y (Resto)
x = comparativa_ols['Capital_Activos']
y = comparativa_ols['Resto_Activos']

# Calculo la Correlación de Pearson (r) y el P-valor
res = stats.pearsonr(x, y)
r = res.statistic
p_valor = res.pvalue

print(f"Coeficiente de Correlación (r): {r:.4f}")
print(f"P-valor: {p_valor}")

# Interpretación
if r > 0:
    print("La correlación es positiva.")
    print("Cuando crece la población de la capital, también crece la del resto de las provincias.")
    print("Esto indica que la capital no estaría absorbiendo población del resto del territorio.")
else:
    print("La correlación es negativa.")
    print("La población de la capital aumenta mientras que la del resto de las provincias disminuye.")
    print("Esto sugiere que la capital actúa como un polo atractor que concentra población.")


# Gráfico de Dispersión con Línea de Tendencia
plt.figure(figsize=(8, 6))

# Puntos de datos
plt.scatter(x, y, color='darkorange', alpha=0.7, label='Datos Anuales')

# Línea de regresión (ajuste lineal simple)
m, b = np.polyfit(x, y, 1)
plt.plot(x, m*x + b, color='blue', linestyle='--', linewidth=2, label=f'Tendencia (r={r:.2f})')

plt.title('Correlación: Población Activa Capital vs Resto de Galicia')
plt.xlabel('Población Activa en A Coruña')
plt.ylabel('Población Activa en Resto de Galicia')
plt.legend()
plt.grid(True, linestyle='--', alpha=0.5)

plt.show()

"""**Mejoramos la visual para entender mejor el grafico**"""

plt.figure(figsize=(10, 6))

# 'cmap="viridis"' usa una escala de colores (de morado a amarillo)
sc = plt.scatter(x, y, c=comparativa_ols.index, cmap='viridis', s=50, alpha=0.8)

# Añadimos una barra lateral para saber qué color es cada año
plt.colorbar(sc, label='Año')

# Línea de tendencia (la mantenemos igual)
m, b = np.polyfit(x, y, 1)
plt.plot(x, m*x + b, color='red', linestyle='--', linewidth=2, label=f'Tendencia Global (r={r:.2f})')

plt.title('Evolución Temporal: Capital vs Resto')
plt.xlabel('Población Activa en A Coruña')
plt.ylabel('Población Activa en Resto de Galicia')
plt.legend()
plt.grid(True, linestyle='--', alpha=0.5)
plt.show()

"""# Analisis e interpretación:

Esta tabla muestra una relación positiva pero débil entre el crecimiento de la población activa en A Coruña y en el resto de Galicia.
La correlación débil (r=0.21) sugiere que, aunque ambas crecen, no lo hacen de forma de forma sincronizada. Podría haber factores específicos de la capital o del resto de la región que afectan de manera diferencial al mercado laboral.

Esto no es congruente con la hipótesis del "polo atractor" en términos de población activa. Si A Coruña estuviera vaciando al resto, la línea azul iría hacia abajo.

El número 0.21 es bajo. Esto nos dice que la relación es débil: no es una dependencia perfecta.

Los puntos de abajo del todo muestran un momento donde el Resto de Galicia se desplomó (bajó mucho en el eje vertical), probablemente durante los años duros de la crisis económica.

Sin embargo, si miras el eje horizontal en esos mismos puntos, A Coruña aguantó mejor el tipo y no retrocedió tanto.

Los puntos de más a la derecha (los años más recientes) están arriba del todo: significa que ambas zonas se han recuperado y están creciendo juntas de nuevo.
"""